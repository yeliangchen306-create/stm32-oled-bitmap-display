static void OLED_ShowCartoon(void)
{
    uint8_t page;
    uint8_t x;
    for (page = 0; page < 8; page++)
    {
        OLED_SetCursor(page, 0);
        for (x = 0; x < 128; x++)
        {
            OLED_WriteData(CartoonBitmap[page * 128 + x]);
        }
    }
}

